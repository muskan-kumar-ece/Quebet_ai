    def register(cls, declaration: CapabilityDeclaration) -> None:
        cls._registry[declaration.capability_id] = declaration

    @classmethod
    def get(cls, capability_id: str) -> Optional[CapabilityDeclaration]:
        cls._ensure_defaults()
        return cls._registry.get(capability_id)

    @classmethod
    def list_all(cls) -> List[CapabilityDeclaration]:
        cls._ensure_defaults()
        return list(cls._registry.values())

